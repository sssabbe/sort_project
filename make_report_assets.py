import csv
from pathlib import Path
import matplotlib.pyplot as plt

base = Path(__file__).resolve().parent
with (base/'benchmark_results.csv').open(encoding='utf-8-sig', newline='') as f:
    rows = list(csv.DictReader(f))

# Получаем уникальные алгоритмы и размеры
algorithms = list(dict.fromkeys(r['algorithm'] for r in rows))
types = ['Случайный', 'Отсортированный', 'Обратный']
sizes = [100, 1000, 10000]

# Цвета для графиков (чтобы было красиво)
colors = ['#1f77b4', '#ff7f0e', '#2ca02c', '#d62728', '#9467bd']

for dtype in types:
    fig, ax = plt.subplots(figsize=(9, 5.5))
    for i, alg in enumerate(algorithms):
        vals=[]
        for n in sizes:
            match=next(r for r in rows if r['data_type']==dtype and r['algorithm']==alg and int(r['size'])==n)
            vals.append(float(match['time_ms_mean']))
        ax.plot(sizes, vals, marker='o', label=alg, color=colors[i], linewidth=2)
        
    ax.set_title(f'Время сортировки: {dtype.lower()} массив', fontsize=14)
    ax.set_xlabel('Размер массива, элементов', fontsize=12)
    ax.set_ylabel('Время выполнения, мс (логарифмическая шкала)', fontsize=12)
    ax.set_xscale('log')
    ax.set_yscale('log')
    ax.set_xticks(sizes, labels=[str(x) for x in sizes])
    ax.grid(True, which='both', linestyle=':', linewidth=0.6)
    ax.legend(fontsize=9)
    fig.tight_layout()
    fig.savefig(base/f'график_{dtype.lower()}.png', dpi=180)
    plt.close(fig)

# Формируем текст с результатами
lookup={(r['algorithm'], int(r['size']), r['data_type']): float(r['time_ms_mean']) for r in rows}
lines = [
'# Результаты экспериментального исследования',
'',
'## Методика',
'',
'Для исследования использована программа проекта. Измерение выполняется с помощью `time.perf_counter()`. Для каждого сочетания размера и типа массива каждый алгоритм запускался один раз. После каждого запуска результат проверялся сравнением с `sorted()`.',
'',
'Исследованы массивы размером 100, 1 000 и 10 000 элементов. Рассматривались три входных состояния: случайный массив, уже отсортированный массив и массив в обратном порядке.',
'',
'## Основные результаты',
'',
'Время указано в миллисекундах; значения получены в одном запуске и могут отличаться на других компьютерах.',
'',
'| Алгоритм | 100 случайных | 1 000 случайных | 10 000 случайных | 10 000 отсортированных | 10 000 обратных |',
'|---|---:|---:|---:|---:|---:|'
]
for alg in algorithms:
    vals=[lookup[(alg,100,'Случайный')],lookup[(alg,1000,'Случайный')],lookup[(alg,10000,'Случайный')],lookup[(alg,10000,'Отсортированный')],lookup[(alg,10000,'Обратный')]]
    lines.append('| '+alg+' | '+' | '.join(f'{x:.3f}' for x in vals)+' |')
lines += [
'',
'## Интерпретация',
'',
'1. На случайном массиве из 10 000 элементов пузырьковая сортировка выполнилась примерно за ' + f"{lookup[('Пузырьковая сортировка',10000,'Случайный')]:.3f}" + ' мс, а быстрая сортировка — за ' + f"{lookup[('Быстрая сортировка',10000,'Случайный')]:.3f}" + ' мс.',
'2. На уже отсортированном массиве пузырьковая сортировка и сортировка вставками показали себя лучше всего благодаря досрочному завершению и быстрому лучшему случаю.',
'3. На массиве в обратном порядке быстрая сортировка и слияние завершились существенно быстрее простых алгоритмов.',
'',
'## Вывод',
'',
'Эксперимент показывает, что простые алгоритмы сортировки могут быть приемлемы на небольших массивах, а на массивах из 10 000 элементов их время выполнения резко увеличивается. Быстрая сортировка и сортировка слиянием в проведённых испытаниях масштабировались заметно лучше.',
'',
'## Графики',
'',
'- `график_случайный.png` — случайные массивы.',
'- `график_отсортированный.png` — уже отсортированные массивы.',
'- `график_обратный.png` — массивы в обратном порядке.',
]
(base/'Результаты_экспериментов.md').write_text('\n'.join(lines), encoding='utf-8')
print("Готово! Созданы графики и файл 'Результаты_экспериментов.md'")